# =============================================================================
# Lil Dude — Windows Install + Scheduled Task Setup
# Creates a scheduled task so Lil Dude starts automatically on login.
# Usage: powershell -ExecutionPolicy Bypass -File scripts/install-windows.ps1
# Flags: -Yes  Skip all interactive prompts
#        -NoService  Skip scheduled task setup
# =============================================================================

param(
    [switch]$Yes,
    [switch]$NoService
)

$ErrorActionPreference = "Stop"

$TaskName = "LilDude"
$TaskDescription = "Lil Dude - Personal AI Executive Assistant"
$ConfigDir = Join-Path $env:USERPROFILE ".lil-dude"
$LogDir = Join-Path $ConfigDir "logs"

# --- Helper functions ---
function Write-Info {
    param([string]$Message)
    Write-Host $Message -ForegroundColor Cyan
}

function Write-Success {
    param([string]$Message)
    Write-Host $Message -ForegroundColor Green
}

function Write-Warn {
    param([string]$Message)
    Write-Host $Message -ForegroundColor Yellow
}

function Write-Error-Msg {
    param([string]$Message)
    Write-Host $Message -ForegroundColor Red
}

# --- Check Windows ---
if ($env:OS -ne "Windows_NT") {
    Write-Error-Msg "  This script is for Windows only."
    exit 1
}

# --- Step 1: Run base install ---
Write-Info "  Running base installer..."
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$BaseInstall = Join-Path $ScriptDir "install.ps1"

if ($Yes) {
    & powershell -ExecutionPolicy Bypass -File $BaseInstall -Yes
} else {
    & powershell -ExecutionPolicy Bypass -File $BaseInstall
}

if ($NoService) {
    Write-Success "  Skipping scheduled task setup (-NoService)"
    exit 0
}

# --- Step 2: Locate lil-dude ---
$LilDudeCmd = Get-Command lil-dude -ErrorAction SilentlyContinue
if (-not $LilDudeCmd) {
    Write-Error-Msg "  Could not find lil-dude binary after installation."
    exit 1
}
$LilDudePath = $LilDudeCmd.Source
Write-Info "  Binary found at: $LilDudePath"

# --- Step 3: Locate node.exe ---
$NodeCmd = Get-Command node -ErrorAction SilentlyContinue
if (-not $NodeCmd) {
    Write-Error-Msg "  Could not find Node.js."
    exit 1
}
$NodePath = $NodeCmd.Source

# --- Step 4: Create directories ---
if (-not (Test-Path $LogDir)) {
    New-Item -ItemType Directory -Path $LogDir -Force | Out-Null
}
Write-Info "  Log directory: $LogDir"

# --- Step 5: Prompt for scheduled task ---
if (-not $Yes) {
    $reply = Read-Host "  Install scheduled task to start Lil Dude on login? [Y/n]"
    if ($reply -match '^[nN]') {
        Write-Info "  Skipping scheduled task setup."
        Write-Info "  Start manually with: lil-dude start"
        exit 0
    }
}

# --- Step 6: Remove existing task ---
$existingTask = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($existingTask) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    Write-Info "  Removed existing scheduled task"
}

# --- Step 7: Create scheduled task ---
$StdOutLog = Join-Path $LogDir "lildude-stdout.log"
$StdErrLog = Join-Path $LogDir "lildude-stderr.log"

# Create a wrapper script for logging
$WrapperScript = Join-Path $ConfigDir "start-lildude.ps1"
$WrapperContent = @"
# Auto-generated by Lil Dude installer — do not edit
`$ErrorActionPreference = "Continue"
try {
    & "$LilDudePath" start *>> "$StdOutLog" 2>> "$StdErrLog"
} catch {
    `$_ | Out-File -Append "$StdErrLog"
}
"@
Set-Content -Path $WrapperScript -Value $WrapperContent -Force

$Action = New-ScheduledTaskAction `
    -Execute "powershell.exe" `
    -Argument "-WindowStyle Hidden -ExecutionPolicy Bypass -File `"$WrapperScript`"" `
    -WorkingDirectory $ConfigDir

$Trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME

$Settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -RestartInterval (New-TimeSpan -Minutes 1) `
    -RestartCount 3 `
    -ExecutionTimeLimit (New-TimeSpan -Days 365)

Register-ScheduledTask `
    -TaskName $TaskName `
    -Description $TaskDescription `
    -Action $Action `
    -Trigger $Trigger `
    -Settings $Settings `
    -RunLevel Limited | Out-Null

Write-Success "  Scheduled task created: $TaskName"

# --- Step 8: Start the task ---
Start-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
Write-Success "  Task started — Lil Dude is running"

Write-Host ""
Write-Info "  Management commands:"
Write-Info "    Status:     Get-ScheduledTask -TaskName $TaskName"
Write-Info "    Stop:       Stop-ScheduledTask -TaskName $TaskName"
Write-Info "    Start:      Start-ScheduledTask -TaskName $TaskName"
Write-Info "    Remove:     Unregister-ScheduledTask -TaskName $TaskName"
Write-Info "    View logs:  Get-Content $StdOutLog -Tail 50 -Wait"
Write-Host ""

exit 0
